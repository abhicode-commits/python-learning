# PYTHON TYPE CASTING

# 1. Integer to String
print("1. Integer to String")

a = 100
b = str(a)

print(b)
print(type(b))


# 2. String to Integer
print("\n2. String to Integer")

a = "50"
b = int(a)

print(b)
print(type(b))


# 3. Integer to Float
print("\n3. Integer to Float")

a = 25
b = float(a)

print(b)
print(type(b))


# 4. Float to Integer
print("\n4. Float to Integer")

a = 25.8
b = int(a)

print(b)
print(type(b))


# 5. String to Float
print("\n5. String to Float")

a = "99.5"
b = float(a)

print(b)
print(type(b))


# 6. Integer to Boolean
print("\n6. Integer to Boolean")

