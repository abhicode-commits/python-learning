# Python Data Types

# 1. Integer (int)
age = 18
marks = 95

print("Integer Examples:")
print(age)
print(marks)
print(type(age))


# 2. String (str)
name = "Abhishek"
city = "Rampur"

print("String Examples:")
print(name)
print(city)
print(type(name))


# 3. Float (float)
percentage = 79.4
price = 99.50

print("Float Examples:")
print(percentage)
print(price)
print(type(percentage))


# 4. Boolean (bool)
is_student = True
is_working = False

print("Boolean Examples:")
print(is_student)
print(is_working)
print(type(is_student))